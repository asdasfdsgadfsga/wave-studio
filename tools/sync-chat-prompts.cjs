// server/*.txt are the source of truth; regenerate the Pages module after editing.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const prompts = [['PRO_PROMPT', 'system_prompt.txt'], ['STREET_PROMPT', 'street_prompt.txt']];
const output = '// Generated by node tools/sync-chat-prompts.cjs. Edit server/*_prompt.txt instead.\n'
  + prompts.map(([name, file]) => `export const ${name} = ${JSON.stringify(fs.readFileSync(path.join(root, 'server', file), 'utf8').replace(/\r\n/g, '\n').trim())};\n`).join('');
const target = path.join(root, 'lib/chat/prompts.mjs');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) {
    console.error('Chat prompts are out of sync. Run: node tools/sync-chat-prompts.cjs');
    process.exitCode = 1;
  }
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, output);
}
